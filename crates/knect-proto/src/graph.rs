//! Graph projection types returned by `graph.get_topology` and related methods.

use std::collections::BTreeMap;

use chrono::{DateTime, Utc};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::ids::ResourceId;
use crate::links::LinkRecord;
use crate::mutation::MutationRecord;
use crate::policy::PolicyRecord;
use crate::storage::StorageRecord;
use crate::tap::LogLine;

/// High-level category used to group resources in the UI and stats.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum NodeCategory {
    KService,
    Route,
    Configuration,
    Revision,
    PodAutoscaler,
    Broker,
    Trigger,
    EventType,
    Source,
    SinkBinding,
    Subscription,
    Channel,
    Sink,
    Deployment,
    ReplicaSet,
    Pod,
    Service,
    Endpoints,
    BackingService,
    Topic,
    StorageClass,
    PersistentVolume,
    PersistentVolumeClaim,
    CephPool,
    Policy,
    Canary,
    VirtualService,
    DestinationRule,
    PeerAuthentication,
    AuthorizationPolicy,
    ConfigMap,
    Secret,
    Namespace,
    #[serde(other)]
    Unknown,
}

/// Semantic relationship between two resources.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum EdgeKind {
    RoutesTo,
    Owns,
    Scales,
    Runs,
    Subscribes,
    DeliversTo,
    DeadLetterSink,
    UsesSecret,
    UsesConfigMap,
    ConnectsTo,
    BackedBy,
    Mounts,
    ProvisionedBy,
    ProtectedBy,
    MutatedBy,
    Manages,
    References,
    Targets,
    PublishedBy,
    ConsumesFrom,
    Selects,
    #[serde(other)]
    Unknown,
}

/// Roll-up health state for a node, edge, or the whole topology.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum Health {
    Healthy,
    Degraded,
    Progressing,
    Blocked,
    #[serde(other)]
    Unknown,
}

/// Severity shared by warnings, badges, and policy records.
#[derive(
    Debug,
    Clone,
    Copy,
    Default,
    PartialEq,
    Eq,
    Hash,
    PartialOrd,
    Ord,
    Serialize,
    Deserialize,
    JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Critical,
    High,
    Medium,
    Low,
    #[default]
    Info,
    #[serde(other)]
    Unknown,
}

/// A short, attributable marker rendered next to a node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Badge {
    /// Display text, for example `scale-to-zero`.
    pub label: String,
    /// Severity used by clients to choose a colour.
    #[serde(default)]
    pub severity: Severity,
    /// Optional hover text.
    pub tooltip: Option<String>,
}

/// A non-fatal problem detected while building or correlating the graph.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Warning {
    /// Stable machine-readable warning code.
    pub code: String,
    /// Human-readable explanation with any secret values removed.
    pub message: String,
    /// Severity used by clients to choose a colour.
    #[serde(default)]
    pub severity: Severity,
    /// Resource the warning belongs to, when known.
    pub resource: Option<ResourceId>,
}

/// A resource vertex in the topology.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ResourceNode {
    /// Canonical resource identity.
    pub id: ResourceId,
    /// UI grouping category.
    pub category: NodeCategory,
    /// Object name; duplicated from `id` for convenient rendering.
    pub name: String,
    /// Namespace, or `None` for cluster-scoped resources.
    pub namespace: Option<String>,
    /// Current health.
    pub health: Health,
    /// One-line description generated by the correlators.
    pub summary: String,
    /// Sanitized labels.
    #[serde(default)]
    pub labels: BTreeMap<String, String>,
    /// Sanitized annotations.
    #[serde(default)]
    pub annotations: BTreeMap<String, String>,
    /// UI badges.
    #[serde(default)]
    pub badges: Vec<Badge>,
    /// Kubernetes UID, when observed.
    pub uid: Option<String>,
    /// First time the object was observed by this daemon.
    #[schemars(with = "String")]
    pub first_seen: DateTime<Utc>,
    /// Most recent time the object was observed.
    #[schemars(with = "String")]
    pub last_seen: DateTime<Utc>,
}

/// A directed relationship between two resources.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Edge {
    /// Stable edge ID, unique within a topology generation.
    pub id: String,
    /// Source resource.
    pub from: ResourceId,
    /// Target resource.
    pub to: ResourceId,
    /// Semantic relationship.
    pub kind: EdgeKind,
    /// Optional display label.
    pub label: Option<String>,
    /// Health of the relationship.
    pub health: Health,
    /// Problems affecting this relationship.
    #[serde(default)]
    pub warnings: Vec<Warning>,
    /// Deterministic, redacted edge-specific metadata.
    #[serde(default)]
    pub metadata: BTreeMap<String, serde_json::Value>,
}

/// The full graph projection.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Topology {
    /// Protocol schema version. See [`crate::SCHEMA_VERSION`].
    pub schema_version: u32,
    /// Kubernetes context name.
    pub context: String,
    /// Monotonic graph generation.
    pub generation: u64,
    /// Resource vertices.
    #[serde(default)]
    pub nodes: Vec<ResourceNode>,
    /// Resource relationships.
    #[serde(default)]
    pub edges: Vec<Edge>,
    /// Non-fatal graph warnings.
    #[serde(default)]
    pub warnings: Vec<Warning>,
    /// Aggregate statistics.
    pub stats: TopologyStats,
}

/// Count of nodes in one category.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CategoryCount {
    /// Category being counted.
    pub category: NodeCategory,
    /// Number of nodes in the category.
    pub count: u64,
}

/// Aggregate topology statistics.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct TopologyStats {
    /// Number of nodes.
    #[serde(default)]
    pub node_count: u64,
    /// Number of edges.
    #[serde(default)]
    pub edge_count: u64,
    /// Number of warnings.
    #[serde(default)]
    pub warning_count: u64,
    /// Per-category node counts, sorted deterministically.
    #[serde(default)]
    pub categories: Vec<CategoryCount>,
    /// True when the graph was truncated by the watch limits.
    #[serde(default)]
    pub truncated: bool,
}

/// Numeric metrics attached to a node when available.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct MetricsSummary {
    /// CPU usage in millicores.
    pub cpu_millicores: Option<f64>,
    /// Memory usage in bytes.
    pub memory_bytes: Option<u64>,
    /// Observed replica count.
    pub replicas: Option<u32>,
    /// Ready replica count.
    pub ready_replicas: Option<u32>,
    /// Requests per second over the observation window.
    pub requests_per_second: Option<f64>,
    /// Fraction of failed requests over the observation window.
    pub error_rate: Option<f64>,
    /// 95th percentile latency in milliseconds.
    pub p95_latency_ms: Option<f64>,
    /// Observation window in seconds.
    pub window_secs: Option<u64>,
    /// Metrics backend or source.
    pub source: Option<String>,
}

/// Full inspector payload for one node.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct NodeDetails {
    /// Identity of the inspected resource.
    pub id: ResourceId,
    /// UI grouping category, copied from the topology node.
    pub category: NodeCategory,
    /// Object name.
    pub name: String,
    /// Namespace, or `None` for cluster-scoped resources.
    pub namespace: Option<String>,
    /// Current health.
    pub health: Health,
    /// One-line description.
    pub summary: String,
    /// Redacted YAML manifest. Secrets and ConfigMap values are removed.
    pub yaml: Option<String>,
    /// True when `yaml` has passed through the daemon redactor.
    #[serde(default = "default_true")]
    pub yaml_redacted: bool,
    /// Fields managed by Kubernetes, controllers, or policy engines.
    #[serde(default)]
    pub mutations: Vec<MutationRecord>,
    /// Policy results affecting this resource.
    #[serde(default)]
    pub policies: Vec<PolicyRecord>,
    /// Inbound and outbound links.
    #[serde(default)]
    pub links: Vec<LinkRecord>,
    /// Storage claims mounted by this resource.
    #[serde(default)]
    pub storage: Vec<StorageRecord>,
    /// Non-fatal details warnings.
    #[serde(default)]
    pub warnings: Vec<Warning>,
    /// Metrics when a metrics source is configured.
    pub metrics: Option<MetricsSummary>,
    /// Recent log lines when `include_logs` was requested.
    #[serde(default)]
    pub logs: Vec<LogLine>,
}

const fn default_true() -> bool {
    true
}
